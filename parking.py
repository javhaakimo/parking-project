import sys
from datetime import datetime
from pathlib import Path


PARKING_FILE = Path(__file__).resolve().parent / "parking.txt"

ЦАГИЙН_ТӨЛБӨР = 1000
ЦАГИЙН_ФОРМАТ = "%Y-%m-%d %H:%M:%S"


def Төлбөр_тооцох(минут):
    цаг = max((минут + 59) // 60, 1)
    return цаг * ЦАГИЙН_ТӨЛБӨР


class ФорматАлдаа(ValueError):
    pass


def _формат_алдаа(мөр, мөрийн_дугаар):
    return ФорматАлдаа(
        f'parking.txt-ийн {мөрийн_дугаар}-р мөр буруу форматтай: "{мөр.strip()}"\n'
        "Зөв формат: ДУГААР - YYYY-MM-DD HH:MM:SS "
        "(жишээ: 1111УБА - 2026-09-23 10:00:00)\n"
        "Энэ мөрийг гараар засаад дахин оролдоно уу."
    )


def _мөр_задлах(мөр, мөрийн_дугаар):
    # Буруу форматтай мөрийн огноог таамаглахгүй, засах заавар өгнө
    мөр = мөр.strip()
    parts = мөр.split(" - ")
    try:
        if len(parts) != 2:
            raise ValueError
        орсон = datetime.strptime(parts[1], ЦАГИЙН_ФОРМАТ)
    except ValueError:
        raise _формат_алдаа(мөр, мөрийн_дугаар) from None
    return parts[0], parts[1], орсон


def _зогссон_минут(орсон, гарсан):
    # Орсон цаг секундээр хадгалагддаг тул гарсан цагийн микросекундийг хаяна.
    # Эхэлсэн минут бүрийг тооцохын тулд дээш тойруулна.
    секунд = int((гарсан.replace(microsecond=0) - орсон).total_seconds())
    return -(-секунд // 60)


def _оролт_авах(асуулт):
    # Python 3.14 дээр input() кирилл оролтыг эвддэг тул readline ашиглана
    print(асуулт, end="", flush=True)
    мөр = sys.stdin.readline()
    if not мөр:
        raise EOFError
    return мөр.rstrip("\r\n")


def _дугаар_авах():
    # Хоосон дугаар бүх мөртэй таарч машинуудыг устгахаас сэргийлж дахин асууна
    while True:
        номер = _оролт_авах("Улсын дугаар: ").strip()
        if номер:
            return номер
        print("===== Улсын дугаар хоосон байна. Дахин оруулна уу.")


def _мөрөөс_дугаар(мөр, мөрийн_дугаар):
    # Тусгаарлагчгүй мөрөөс дугаар таамаглахгүй, засах заавар өгнө
    if " - " not in мөр:
        raise _формат_алдаа(мөр, мөрийн_дугаар)
    return мөр.split(" - ", 1)[0].strip()


def Машин_оруулах():
    номер = _дугаар_авах()
    цаг = datetime.now().strftime(ЦАГИЙН_ФОРМАТ)
    
    with open(PARKING_FILE, "a", encoding="utf-8") as file:
        file.write(f'{номер} - {цаг}\n')
        
        return "<<Амжилттай нэвтэрлээ>>"

def Машин_гарах():
    номер = _дугаар_авах()
    гарсан_цаг = datetime.now()
    found = False
    
    Жагсаалт = []
    
                 
    with open(PARKING_FILE, "r", encoding="utf-8") as file:
        мөрүүд = list(file)

    # Юу ч хэвлэх, бичихээс өмнө бүх мөрийг шалгана: сүүлийн мөр алдаатай бол
    # машин "гарсан" гэж хэвлэгдээд файлд үлдэх, дахин төлбөр авахаас сэргийлнэ
    таарсан = {}
    for мөрийн_дугаар, номерцаг in enumerate(мөрүүд, 1):
        if _мөрөөс_дугаар(номерцаг, мөрийн_дугаар) == номер:
            таарсан[мөрийн_дугаар] = _мөр_задлах(номерцаг, мөрийн_дугаар)

    for мөрийн_дугаар, номерцаг in enumerate(мөрүүд, 1):
        if мөрийн_дугаар in таарсан:
            _, орсон_цаг, орсон = таарсан[мөрийн_дугаар]

            if гарсан_цаг.replace(microsecond=0) < орсон:
                print("===== Гарсан цаг орсон цагаас өмнө байна:", орсон_цаг)
                Жагсаалт.append(номерцаг)
                found = True
                continue

            зогссон_минут = _зогссон_минут(орсон, гарсан_цаг)
            зогссон_цаг = зогссон_минут // 60
            үлдсэн_минут = зогссон_минут % 60
            төлбөр = Төлбөр_тооцох(зогссон_минут)

            print("Орсон цаг:", орсон_цаг)
            print(f"Зогссон хугацаа: {зогссон_цаг} цаг {үлдсэн_минут} минут")
            print(f"Төлбөр: {төлбөр}₮")
            print("===== Машин олдлоо:", номерцаг)
            found = True

        else:
            Жагсаалт.append(номерцаг)

    with open(PARKING_FILE, "w", encoding="utf-8") as file:
        for номерцаг in  Жагсаалт:
            file.write(номерцаг)      
                              
    if found == False:
        print("===== Машин олдсонгүй")            
        
        


def Машин_устгах():
    Жагсаалт = []
    номер = _дугаар_авах()

    with open(PARKING_FILE, "r", encoding="utf-8") as file:
        for мөрийн_дугаар, номерцаг in enumerate(file, 1):
            if _мөрөөс_дугаар(номерцаг, мөрийн_дугаар) != номер:
                Жагсаалт.append(номерцаг)  
                
    with open(PARKING_FILE, "w", encoding="utf-8") as file:
        for номерцаг in Жагсаалт:
            file.write(номерцаг)
                   
    return ("===== Машин устлаа")     
        
def Машинууд_харах():
    одоо = datetime.now()
    машинууд = []

    with open(PARKING_FILE, "r", encoding="utf-8") as file:
        for мөрийн_дугаар, мөр in enumerate(file, 1):
            номер, орсон_цаг, орсон = _мөр_задлах(мөр, мөрийн_дугаар)
            зогссон_минут = max(_зогссон_минут(орсон, одоо), 0)

            зогссон_цаг = зогссон_минут // 60
            үлдсэн_минут = зогссон_минут % 60
            машинууд.append(
                f"{номер} - Орсон: {орсон_цаг} - Зогссон: "
                f"{зогссон_цаг} цаг {үлдсэн_минут} минут"
            )

    return "\n".join(машинууд)
      
def Нийт_машин():
    машинууд = []
    
    with open(PARKING_FILE, "r", encoding="utf-8") as file:
        for номерцаг in file:
            машинууд.append(номерцаг)
    
    return len(машинууд) 
       
       
        
def main():
    while True:
        print("\n1. Машин_оруулах")
        print("2. Машин_гарах")
        print("3. Машин_устгах")
        print("4. Машинууд_харах")
        print("5. Нийт_машин")
        print("6. Exit")

        choice = _оролт_авах("Сонголт: ")

        try:
            if choice == "1":
                print(Машин_оруулах())

            elif choice == "2":
                Машин_гарах()

            elif choice == "3":
                print(Машин_устгах())

            elif choice == "4":
                print(Машинууд_харах())

            elif choice == "5":
                print(Нийт_машин())

            elif choice == "6":
                break
        except ФорматАлдаа as алдаа:
            print("===== Алдаа:", алдаа)


if __name__ == "__main__":
    main()
